// JS code generation from HIR (spec §14.2). The output is an ES module that imports the runtime
// (src/js/runtime.ts) as `$rt` and exports `$main()`.
//
// MinScript has block / if / match expressions and JS doesn't, so the emitter has two modes:
// - `expr(e)` returns a JS expression, first emitting any statements it needs into the current block;
// - `into(e, target)` compiles `e` as statements, then discards its value, assigns it, or returns it.
// When a later argument needs statements, earlier (impure) arguments are spilled to temporaries first,
// so evaluation stays left to right. Every `break` / `continue` is labelled, so the emitter's own
// loops (`select`, `continue` with a step) never capture them.

import type * as H from "../hir.ts"
import type { Sym } from "../resolve.ts"
import * as T from "../types.ts"
import type { Ty } from "../types.ts"

/** `entry`: the function `$main` calls (default `main`; `mod.config` when evaluating mod.ms). */
export function emitJs(p: H.Program, runtimeUrl: string, entry = "main"): string {
    return new Emitter(p).module(runtimeUrl, entry)
}

// ---------------------------------------------------------------------------------------------

type Target = { kind: "discard" } | { kind: "assign", name: string } | { kind: "return" }
const DISCARD: Target = { kind: "discard" }
const RETURN: Target = { kind: "return" }

const RESERVED = new Set([
    "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else", "enum", "export",
    "extends", "false", "finally", "for", "function", "if", "import", "in", "instanceof", "new", "null", "return", "super",
    "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with", "yield", "let", "static", "await",
    "implements", "interface", "package", "private", "protected", "public", "arguments", "eval", "undefined", "NaN", "Infinity",
])

type LoopCtx = { hir: string | null, js: string, body: string | null, target: string | null }

const isPure = (code: string) => /^[A-Za-z_$][\w$]*$/.test(code) || /^-?\d+(\.\d+)?n?$/.test(code) || /^"([^"\\]|\\.)*"$/.test(code) || code === "undefined"

function indent(lines: string[]): string[] {
    return lines.flatMap((l) => l.split("\n")).map((l) => (l === "" ? l : `    ${l}`))
}

class Emitter {
    private readonly program: H.Program
    private readonly userFuns = new Map<string, H.Fun>()
    private out: string[] = []
    private names = new Map<Sym, string>()
    private used = new Set<string>()
    private temps = 0
    private loops: LoopCtx[] = []
    private labels = 0

    private readonly globals = new Set<string>()
    /** the type witnesses of the function being emitted */
    private witnesses = new Set<Sym>()

    constructor(p: H.Program) {
        this.program = p
        for (const f of p.funs) if (!f.builtin) this.userFuns.set(f.name, f)
        for (const g of p.globals) this.globals.add(g.name)
    }

    // ---- module -------------------------------------------------------------------------------

    module(runtimeUrl: string, entry: string): string {
        const lines: string[] = [
            "// Generated by the MinScript compiler. Do not edit.",
            `import * as $rt from ${JSON.stringify(runtimeUrl)}`,
            "",
        ]
        for (const f of this.program.funs) if (!f.builtin) lines.push(...this.fun(f), "")
        // std functions written in MinScript: dynamic calls (`$rt.dyn(v, "map")`) find them by name
        const compiledStd = this.program.funs.filter((f) => !f.builtin && f.name.startsWith("std."))
        if (compiledStd.length > 0) lines.push(`$rt.defStd({ ${compiledStd.map((f) => `${JSON.stringify(f.name.slice(4))}: ${this.fnName(f.name)}`).join(", ")} })`, "")
        // the type registry: methods for dynamic dispatch, field names for printing
        for (const t of this.program.types) lines.push(this.typeDef(t))
        lines.push("")
        for (const g of this.program.globals) {
            this.resetFn()
            const code = this.expr(g.value)
            lines.push(...this.out, `const ${this.fnName(g.name)} = ${code}`)
        }
        const hasMain = this.userFuns.has(entry)
        lines.push("", `export async function $main() { ${hasMain ? `return await ${this.fnName(entry)}()` : ""} }`, "")
        return lines.join("\n")
    }

    private typeDef(t: H.TypeDef): string {
        const methods = (owner: string) => {
            const entries = this.program.funs.filter((f) => f.name.startsWith(`${owner}.`) && !f.name.slice(owner.length + 1).includes("."))
                .map((f) => `${JSON.stringify(f.name.slice(owner.length + 1))}: ${this.fnName(f.name)}`)
            return `{ ${entries.join(", ")} }`
        }
        switch (t.kind) {
            case "struct": {
                const floats = t.fields.filter((f) => f.float).map((f) => f.name)
                const shapes = Object.fromEntries(t.fields.filter((f) => f.shape).map((f) => [f.name, f.shape]))
                const defaults = t.fields.filter((f) => f.default).map((f) => {
                    this.resetFn()
                    const code = this.expr(f.default!)
                    return `${JSON.stringify(f.name)}: () => { ${this.out.join(" ")} return ${code} }`
                })
                return `$rt.defType(${JSON.stringify(t.name)}, "struct", ${JSON.stringify(t.fields.map((f) => f.name))}, ${methods(t.name)}, ${JSON.stringify(t.interfaces)}, ${JSON.stringify(floats)}, ${JSON.stringify(shapes)}, { ${defaults.join(", ")} })`
            }
            case "union": {
                const fields = Object.fromEntries(t.variants.map((v) => [v.name, v.fields.map((f) => f.name)]))
                const floats = t.variants.flatMap((v) => v.fields.filter((f) => f.float).map((f) => `${v.name}.${f.name}`))
                return `$rt.defType(${JSON.stringify(t.name)}, "union", ${JSON.stringify(fields)}, ${methods(t.name)}, ${JSON.stringify(t.interfaces)}, ${JSON.stringify(floats)})`
            }
            case "inter": return `$rt.defInter(${JSON.stringify(t.name)}, ${methods(t.name)})`
        }
    }

    private resetFn(): void {
        this.witnesses = new Set()
        this.out = []
        this.names = new Map()
        this.used = new Set()
        this.temps = 0
        this.loops = []
        this.labels = 0
    }

    private fun(f: H.Fun): string[] {
        this.resetFn()
        const params: string[] = []
        const prologue: string[] = []
        const cells: string[] = []
        if (f.self) params.push(this.local(f.self.sym))
        for (const p of f.params) {
            const name = this.local(p.sym)
            if (needsCell(p.ty)) {
                const cell = `$c_${name}`
                params.push(cell)
                prologue.push(`let ${name} = ${cell}.v`)
                cells.push(`${cell}.v = ${name}`)
            } else {
                params.push(name)
            }
        }
        // type witnesses: hidden parameters, after the others (spec §14.1)
        this.witnesses = new Set(f.witnesses ?? [])
        for (const w of f.witnesses ?? []) params.push(witnessVar(w))
        const async = f.async || f.name === "main"
        const head = `${async ? "async " : ""}function ${this.fnName(f.name)}(${params.join(", ")})`
        if (f.body === null) return [`${head} { $rt.panic(${JSON.stringify(`extern function \`${f.name}\` is not available on the JS back end`)}) }`]
        this.out = []
        this.blockInto(f.body, RETURN)
        const body = cells.length > 0 ? [...prologue, "try {", ...indent(this.out), `} finally { ${cells.join("; ")} }`] : this.out
        return [`${head} {`, ...indent(body), "}"]
    }

    // ---- names --------------------------------------------------------------------------------

    private local(sym: Sym): string {
        const known = this.names.get(sym)
        if (known !== undefined) return known
        let base = sym.kind === "this" ? "self" : sym.name === "it1" ? "it" : sym.name
        base = base.replace(/[^\w$]/g, "_")
        if (RESERVED.has(base)) base += "_"
        let name = base
        for (let n = 2; this.used.has(name); n++) name = `${base}_${n}`
        this.used.add(name)
        this.names.set(sym, name)
        return name
    }

    private tmp(prefix = "$t"): string {
        let name = `${prefix}${++this.temps}`
        while (this.used.has(name)) name = `${prefix}${++this.temps}`
        this.used.add(name)
        return name
    }

    /** A compiled function or global is a local identifier; anything else in std is the runtime's. */
    private fnName(name: string): string {
        if (name.startsWith("std.") && !this.userFuns.has(name) && !this.globals.has(name)) return `$rt.std[${JSON.stringify(name.slice(4))}]`
        const js = name.replace(/\./g, "$")
        return RESERVED.has(js) ? `${js}_` : js
    }

    private isCtorName(name: string): boolean {
        const last = name.slice(name.lastIndexOf(".") + 1)
        return /^[A-Z]/.test(last) && !this.userFuns.has(name)
    }

    // ---- statement buffers --------------------------------------------------------------------

    private capture(fn: () => void): string[] {
        const saved = this.out
        this.out = []
        try {
            fn()
            return this.out
        } finally {
            this.out = saved
        }
    }

    private emit(line: string): void {
        this.out.push(line)
    }

    private emitBlock(head: string, body: string[], tail = "}"): void {
        this.out.push(`${head} {`, ...indent(body), tail)
    }

    private assignTarget(target: Target, code: string): void {
        switch (target.kind) {
            case "discard":
                if (!isPure(code)) this.emit(`${code.startsWith("{") || code.startsWith("function") ? `(${code})` : code};`)
                return
            case "assign": this.emit(`${target.name} = ${code};`); return
            case "return": this.emit(`return ${code};`); return
        }
    }

    /** Evaluates expressions in order, spilling earlier impure ones when a later one needs statements. */
    private exprs(list: H.Expr[]): string[] {
        const codes: string[] = []
        for (const x of list) {
            const mark = this.out.length
            const c = this.expr(x)
            if (this.out.length > mark) {
                const spills: string[] = []
                for (let j = 0; j < codes.length; j++) {
                    if (isPure(codes[j]!)) continue
                    const t = this.tmp()
                    spills.push(`const ${t} = ${codes[j]};`)
                    codes[j] = t
                }
                this.out.splice(mark, 0, ...spills)
            }
            codes.push(c)
        }
        return codes
    }

    // ---- blocks and statements ----------------------------------------------------------------

    private blockInto(b: H.Block, target: Target): void {
        for (const s of b.stmts) {
            if (s.k === "let") {
                const code = this.expr(s.value)
                this.emit(`let ${this.local(s.local.sym)} = ${code};`)
            } else {
                this.into(s.expr, DISCARD)
            }
        }
        if (b.value !== null) this.into(b.value, target)
        else if (target.kind === "return") { /* falls off: returns undefined (unit) */ }
    }

    /** Compiles `e` as statements; its value goes to `target`. */
    private into(e: H.Expr, target: Target): void {
        switch (e.k) {
            case "if": {
                const cond = this.expr(e.cond)
                const then = this.capture(() => this.blockInto(e.then, target))
                if (e.else === null) { this.emitBlock(`if (${cond})`, then); return }
                const els = this.capture(() => this.blockInto(e.else!, target))
                this.out.push(`if (${cond}) {`, ...indent(then), "} else {", ...indent(els), "}")
                return
            }
            case "match": return this.match(e, target)
            case "loop": return this.loop(e, target)
            case "block": {
                const body = this.capture(() => this.blockInto(e.block, target))
                this.emitBlock("", body)
                return
            }
            case "select": return this.select(e, target)
            case "recover": return this.recover(e, target)
            case "return":
                this.emit(e.value === null ? "return;" : `return ${this.expr(e.value)};`)
                return
            case "break": {
                const loop = this.findLoop(e.label)
                if (e.value !== null) {
                    const v = this.expr(e.value)
                    if (loop?.target) this.emit(`${loop.target} = ${v};`)
                    else this.assignTarget(DISCARD, v)
                }
                this.emit(loop ? `break ${loop.js};` : "break;")
                return
            }
            case "continue": {
                const loop = this.findLoop(e.label)
                this.emit(!loop ? "continue;" : loop.body ? `break ${loop.body};` : `continue ${loop.js};`)
                return
            }
            case "assign": this.assign(e); return
            case "and": case "or": {
                const code = this.expr(e)
                this.assignTarget(target, code)
                return
            }
            default:
                this.assignTarget(target, this.expr(e))
        }
    }

    private findLoop(label: string | null): LoopCtx | undefined {
        for (let i = this.loops.length - 1; i >= 0; i--) {
            const l = this.loops[i]!
            if (label === null || l.hir === label) return l
        }
        return undefined
    }

    /** A statement-only form used as a value: a temporary receives the value. */
    private viaTemp(e: H.Expr): string {
        const t = this.tmp()
        this.emit(`let ${t};`)
        this.into(e, { kind: "assign", name: t })
        return t
    }

    // ---- control flow -------------------------------------------------------------------------

    private loop(e: Extract<H.Expr, { k: "loop" }>, target: Target): void {
        if (target.kind === "return") {
            const t = this.tmp()
            this.emit(`let ${t};`)
            this.loop(e, { kind: "assign", name: t })
            this.emit(`return ${t};`)
            return
        }
        const js = e.label ? `L_${e.label}_${++this.labels}` : `L${++this.labels}`
        const ctx: LoopCtx = { hir: e.label, js, body: e.step ? `${js}_body` : null, target: target.kind === "assign" ? target.name : null }
        this.loops.push(ctx)
        try {
            const body = this.capture(() => {
                if (e.step) {
                    const inner = this.capture(() => this.blockInto(e.body, DISCARD))
                    this.emitBlock(`${ctx.body}:`, inner)
                    this.blockInto(e.step, DISCARD)
                } else {
                    this.blockInto(e.body, DISCARD)
                }
            })
            this.emitBlock(`${js}: for (;;)`, body)
        } finally {
            this.loops.pop()
        }
    }

    private match(e: Extract<H.Expr, { k: "match" }>, target: Target): void {
        let subject = this.expr(e.subject)
        if (!isPure(subject)) {
            const s = this.tmp("$s")
            this.emit(`const ${s} = ${subject};`)
            subject = s
        }
        const label = `M${++this.labels}`
        const arms = this.capture(() => {
            for (const arm of e.arms) {
                const binds: string[] = []
                const test = this.test(arm.pattern, subject, binds, e.subject.ty)
                const body = this.capture(() => {
                    if (arm.guard !== null) {
                        const guard = this.capture(() => {
                            this.into(arm.body, target)
                            this.emit(`break ${label};`)
                        })
                        const g = this.expr(arm.guard)
                        this.emitBlock(`if (${g})`, guard)
                    } else {
                        this.into(arm.body, target)
                        this.emit(`break ${label};`)
                    }
                })
                const armLines = test === "true" ? body : [`if (${test}) {`, ...indent(body), "}"]
                this.emitBlock("", binds.length > 0 ? [`let ${binds.join(", ")};`, ...armLines] : armLines)
            }
            this.emit(`$rt.panic("no match arm matched", "Unwrap");`)
        })
        this.emitBlock(`${label}:`, arms)
    }

    private select(e: Extract<H.Expr, { k: "select" }>, target: Target): void {
        const waits = this.exprs(e.arms.map((a) => a.wait))
        const sel = this.tmp("$sel")
        this.emit(`const ${sel} = new $rt.Selector([${waits.join(", ")}], ${e.else !== null});`)
        const label = `S${++this.labels}`
        const i = this.tmp("$i"), x = this.tmp("$x")
        const body = this.capture(() => {
            this.emit(`const [${i}, ${x}] = await ${sel}.next();`)
            e.arms.forEach((arm, n) => {
                const binds: string[] = []
                const test = this.test(arm.pattern, x, binds, T.UNKNOWN)
                const run = this.capture(() => {
                    this.emit(`${sel}.done(${n});`)
                    this.into(arm.body, target)
                    this.emit(`break ${label};`)
                })
                const lines = test === "true" ? run : [`if (${test}) {`, ...indent(run), "}", `${sel}.disable(${n});`, `continue ${label};`]
                this.emitBlock(`if (${i} === ${n})`, binds.length > 0 ? [`let ${binds.join(", ")};`, ...lines] : lines)
            })
            if (e.else !== null) {
                const run = this.capture(() => {
                    this.into(e.else!, target)
                    this.emit(`break ${label};`)
                })
                this.emitBlock(`if (${i} === -1)`, run)
            }
        })
        this.emitBlock(`${label}: for (;;)`, body)
    }

    private recover(e: Extract<H.Expr, { k: "recover" }>, target: Target): void {
        const r = this.tmp("$r"), v = this.tmp("$v"), err = this.tmp("$e")
        this.emit(`let ${r};`)
        const body = this.capture(() => {
            this.emit(`let ${v};`)
            this.blockInto(e.body, { kind: "assign", name: v })
            this.emit(`${r} = $rt.Ok(${v});`)
        })
        this.out.push("try {", ...indent(body), `} catch (${err}) {`, `    ${r} = $rt.Err($rt.panicValue(${err}));`, "}")
        this.assignTarget(target, r)
    }

    // ---- patterns -----------------------------------------------------------------------------

    /** A JS condition testing `subject` against `p`; bindings are assigned inside it (declared in `binds`). */
    private test(p: H.Pattern, subject: string, binds: string[], ty: Ty): string {
        const and = (parts: string[]) => {
            const real = parts.filter((x) => x !== "true")
            return real.length === 0 ? "true" : real.join(" && ")
        }
        switch (p.k) {
            case "wild": return "true"
            case "bind": {
                const name = this.local(p.local.sym)
                if (!binds.includes(name)) binds.push(name)      // or-patterns bind the same names in every alternative
                return `((${name} = ${subject}), true)`
            }
            case "lit": return p.value === null ? "true" : `${subject} === ${this.litCode(p.value, ty)}`
            case "range": {
                const parts: string[] = []
                if (p.start !== null) parts.push(`${subject} >= ${this.litCode(p.start, ty)}`)
                if (p.end !== null) parts.push(`${subject} ${p.inclusive ? "<=" : "<"} ${this.litCode(p.end, ty)}`)
                return `(${and(parts)})`
            }
            case "variant":
                return `(${and([`${subject}.$v === ${JSON.stringify(p.variant)}`, ...p.fields.map((f, i) => this.test(f, `${subject}.$f[${i}]`, binds, T.UNKNOWN))])})`
            case "ok": return `(${and([`$rt.isOk(${subject})`, this.test(p.value, `${subject}.$f[0]`, binds, T.UNKNOWN)])})`
            case "fail": return `(${and([`!$rt.isOk(${subject})`, this.test(p.payload, `${subject}.$f[0]`, binds, T.UNKNOWN)])})`
            case "fields": return `(${and(p.fields.map((f) => this.test(f.pattern, `${subject}.${f.name}`, binds, T.UNKNOWN)))})`
            case "tuple": {
                const s = T.strip(ty)
                return `(${and(p.elems.map((el, i) => this.test(el, `${subject}[${i}]`, binds, s.k === "tuple" ? s.elems[i] ?? T.UNKNOWN : T.UNKNOWN)))})`
            }
            case "or": return `(${p.alts.map((a) => this.test(a, subject, binds, ty)).join(" || ")})`
        }
    }

    private litCode(v: bigint | number | string | boolean | null, ty: Ty): string {
        if (v === null) return "undefined"
        if (typeof v === "bigint") return isBig(ty) ? `${v}n` : String(Number(v))
        if (typeof v === "number") return v < 0 ? `(${v})` : String(v)
        if (typeof v === "string") return JSON.stringify(v)
        return String(v)
    }

    // ---- expressions --------------------------------------------------------------------------

    private expr(e: H.Expr): string {
        switch (e.k) {
            case "lit": {
                if (typeof e.value === "bigint") {
                    const code = isBig(e.ty) ? `${e.value}n` : String(Number(e.value))
                    return e.value < 0n ? `(${code})` : code
                }
                return this.litCode(e.value, e.ty)
            }
            case "char": return JSON.stringify(e.value)
            case "local": return this.local(e.sym)
            case "global": return this.fnName(e.name)
            case "fn": {
                if (this.isCtorName(e.name)) {
                    const at = e.name.lastIndexOf(".")
                    return `$rt.ctor(${JSON.stringify(e.name.slice(0, at))}, ${JSON.stringify(e.name.slice(at + 1))})`
                }
                return this.fnName(e.name)
            }
            case "call": return this.call(e)
            case "dyncall": {
                const [recv, ...args] = this.exprs([e.recv, ...e.args])
                return `$rt.dyn(${recv}, ${JSON.stringify(e.method)}, [${args.join(", ")}])`
            }
            case "callvalue": {
                const [callee, ...args] = this.exprs([e.callee, ...e.args])
                const ft = T.strip(e.callee.ty)
                const cellParams = ft.k === "fn" ? ft.params.map(needsCell) : []
                return this.callWithCells(`(${callee})`, args, e.args, cellParams)
            }
            case "wstatic": {
                const args = this.exprs(e.args)
                return `$rt.wstatic(${this.witnessCode(e.witness)}, ${JSON.stringify(e.method)}, [${args.join(", ")}])`
            }
            case "extern": {
                if (e.args === null) return `$rt.ext(${JSON.stringify(e.path)})`
                const args = this.exprs(e.args)
                if (e.typeArgs) args.push(JSON.stringify(e.typeArgs.map((t) => ({ s: t }))))
                return `$rt.ext(${JSON.stringify(e.path)})(${args.join(", ")})`
            }
            case "struct": {
                const codes = this.exprs(e.fields.map((f) => f.value))
                return `({ $t: ${JSON.stringify(e.type)}${e.fields.map((f, i) => `, ${JSON.stringify(f.name)}: ${codes[i]}`).join("")} })`
            }
            case "variant": {
                if (e.union === "std.Option" && e.variant === "None") return "$rt.None"
                return `({ $t: ${JSON.stringify(e.union)}, $v: ${JSON.stringify(e.variant)}, $f: [${this.exprs(e.fields).join(", ")}] })`
            }
            case "record": {
                const codes = this.exprs(e.fields.map((f) => f.value))
                return `({ ${e.fields.map((f, i) => `${JSON.stringify(f.name)}: ${codes[i]}`).join(", ")} })`
            }
            case "tuple": return `[${this.exprs(e.elems).join(", ")}]`
            case "vec": case "array": return `[${this.elems(e.elems).join(", ")}]`
            case "set": return `$rt.setOf([${this.elems(e.elems).join(", ")}])`
            case "map": {
                const flat: H.Expr[] = []
                for (const en of e.entries) if ("k" in en) flat.push(en.expr); else flat.push(en.key, en.value)
                const codes = this.exprs(flat)
                let i = 0
                const parts = e.entries.map((en) => ("k" in en ? `...$rt.entries(${codes[i++]})` : `[${codes[i++]}, ${codes[i++]}]`))
                return `$rt.mapOf([${parts.join(", ")}])`
            }
            case "range": {
                const [a, b] = this.exprs([e.start ?? nullLit(e), e.end ?? nullLit(e)])
                return `$rt.range(${a}, ${b}, ${e.inclusive})`
            }
            case "field": {
                const obj = this.expr(e.object)
                if (/^\d+$/.test(e.name)) {
                    return T.strip(e.object.ty).k === "tuple" ? `${obj}[${e.name}]` : `$rt.idx(${obj}, ${e.name})`
                }
                return `${obj}.${e.name}`
            }
            case "index": {
                const [o, i] = this.exprs([e.object, e.index])
                return e.map ? `$rt.mapGet(${o}, ${i})` : `$rt.at(${o}, ${i})`
            }
            case "unary": {
                const x = this.expr(e.expr)
                switch (e.op) {
                    case "neg": return `(-${x})`
                    case "not": return `(!${x})`
                    case "bitnot": return `(~${x})`
                    case "deref": return `$rt.panic("raw pointers are not available on the JS back end")`
                }
            }
            // falls through
            case "binary": return this.binary(e as Extract<H.Expr, { k: "binary" }>)
            case "and": case "or": {
                const left = this.expr(e.left)
                let right = ""
                const stmts = this.capture(() => { right = this.expr(e.right) })
                const op = e.k === "and" ? "&&" : "||"
                if (stmts.length === 0) return `(${left} ${op} ${right})`
                const t = this.tmp()
                this.emit(`let ${t} = ${left};`)
                this.emitBlock(`if (${e.k === "and" ? t : `!${t}`})`, [...stmts, `${t} = ${right};`])
                return t
            }
            case "truthy": return `$rt.isOk(${this.expr(e.expr)})`
            case "concat": {
                if (e.parts.length === 0) return `""`
                const codes = this.exprs(e.parts)
                return codes.length === 1 ? codes[0]! : `(${codes.join(" + ")})`
            }
            case "tostr": {
                const x = this.expr(e.expr)
                return T.isFloat(T.strip(e.expr.ty)) ? `$rt.toStrF(${x})` : `$rt.toStr(${x})`
            }
            case "widen": return `BigInt(${this.expr(e.expr)})`
            case "cast": return this.cast(e)
            case "await": return `(await ${this.expr(e.expr)})`
            case "closure": return this.closure(e)
            case "unsupported": return `$rt.panic(${JSON.stringify(`not supported on the JS back end: ${e.what}`)})`
            case "assign": {
                this.assign(e)
                return "undefined"
            }
            case "if": case "match": case "loop": case "block": case "select": case "recover":
            case "return": case "break": case "continue":
                return this.viaTemp(e)
        }
    }

    /** A shape as JS; a generic parameter of this function is its witness parameter (null if it has none). */
    private witnessCode(s: H.Shape | null): string {
        if (s === null) return "null"
        if ("param" in s) return this.witnesses.has(s.param) ? witnessVar(s.param) : "null"
        if ("vec" in s) return `{ vec: ${this.witnessCode(s.vec)} }`
        if ("opt" in s) return `{ opt: ${this.witnessCode(s.opt)} }`
        if ("map" in s) return `{ map: ${this.witnessCode(s.map)} }`
        return JSON.stringify(s)
    }

    private elems(list: (H.Expr | H.Spread)[]): string[] {
        const codes = this.exprs(list.map((x) => (x.k === "spread" ? x.expr : x)))
        return list.map((x, i) => (x.k === "spread" ? `...${codes[i]}` : codes[i]!))
    }

    private call(e: Extract<H.Expr, { k: "call" }>): string {
        const args = this.exprs(e.args)
        if (e.shapes) args.push(`[${e.shapes.map((s) => this.witnessCode(s)).join(", ")}]`)     // a builtin's type arguments (`json.parse.[User]`)
        const fn = this.userFuns.get(e.fn)
        for (const w of fn?.witnesses ?? []) {
            const given = e.witnessArgs?.find(([s]) => s === w)
            args.push(this.witnessCode(given ? given[1] : null))
        }
        const cellParams = fn ? [...(fn.self ? [false] : []), ...fn.params.map((p) => needsCell(p.ty))] : []
        return this.callWithCells(this.fnName(e.fn), args, e.args, cellParams)
    }

    /**
     * Calls `fn`; an argument for a `&mut T` parameter is passed in a cell `{ v }` and written back
     * after the call, so assignments inside the callee reach the caller's variable.
     */
    private callWithCells(fn: string, args: string[], argExprs: H.Expr[], cellParams: boolean[]): string {
        if (!cellParams.some(Boolean)) return `${fn}(${args.join(", ")})`
        const passed: string[] = []
        const writeBack: string[] = []
        args.forEach((a, i) => {
            if (!cellParams[i]) { passed.push(a); return }
            const c = this.tmp("$cell")
            this.emit(`const ${c} = { v: ${a} };`)
            passed.push(c)
            const place = argExprs[i]
            if (place && (place.k === "local" || place.k === "field")) writeBack.push(`${a} = ${c}.v;`)
        })
        const r = this.tmp("$r")
        this.emit(`const ${r} = ${fn}(${passed.join(", ")});`)
        for (const w of writeBack) this.emit(w)
        return r
    }

    private binary(e: Extract<H.Expr, { k: "binary" }>): string {
        const [l, r] = this.exprs([e.left, e.right])
        const lt = T.strip(e.left.ty), rt = T.strip(e.right.ty)
        const big = isBig(lt) || isBig(rt)
        switch (e.op) {
            case "/":
                if (big) return `$rt.bdiv(${l}, ${r})`
                if (T.isInt(lt)) return `$rt.idiv(${l}, ${r})`
                break
            case "%":
                if (big) return `$rt.brem(${l}, ${r})`
                if (T.isInt(lt)) return `$rt.irem(${l}, ${r})`
                break
            case "==": case "!=": {
                const primitive = (t: Ty) => t.k === "prim" || t.k === "lit" || t.k === "union"
                if (primitive(lt) && primitive(rt)) return `(${l} ${e.op}= ${r})`
                return e.op === "==" ? `$rt.eq(${l}, ${r})` : `(!$rt.eq(${l}, ${r}))`
            }
        }
        return `(${l} ${e.op} ${r})`
    }

    private cast(e: Extract<H.Expr, { k: "cast" }>): string {
        const x = this.expr(e.expr)
        const from = T.strip(e.expr.ty), to = T.strip(e.to)
        const isChar = (t: Ty) => t.k === "prim" && t.name === "char"
        if (isChar(from) && T.isInt(to)) return isBig(to) ? `BigInt(${x}.codePointAt(0))` : `${x}.codePointAt(0)`
        if (T.isInt(from) && isChar(to)) return `String.fromCodePoint(Number(${x}))`
        if (isBig(to)) return isBig(from) ? x : `BigInt(Math.trunc(${x}))`
        if (T.isInt(to)) return isBig(from) ? `Number(${x})` : T.isFloat(from) ? `Math.trunc(${x})` : x
        if (T.isFloat(to)) return isBig(from) ? `Number(${x})` : x
        return x
    }

    private assign(e: Extract<H.Expr, { k: "assign" }>): void {
        const t = e.target
        const op = e.op
        const ty = T.strip(t.ty)
        const combine = (cur: string, v: string) => {
            const bin = op.slice(0, -1)
            if (bin === "/") return isBig(ty) ? `$rt.bdiv(${cur}, ${v})` : T.isInt(ty) ? `$rt.idiv(${cur}, ${v})` : `(${cur} / ${v})`
            if (bin === "%") return isBig(ty) ? `$rt.brem(${cur}, ${v})` : T.isInt(ty) ? `$rt.irem(${cur}, ${v})` : `(${cur} % ${v})`
            return `(${cur} ${bin} ${v})`
        }
        if (t.k === "index") {
            const [o, i, v] = this.exprs([t.object, t.index, e.value])
            const read = t.map ? `$rt.mapGet(${o}, ${i})` : `$rt.at(${o}, ${i})`
            const value = op === "=" ? v! : combine(read, v!)
            this.emit(t.map ? `${o}.set(${i}, ${value});` : `$rt.setAt(${o}, ${i}, ${value});`)
            return
        }
        if (t.k === "unary" && t.op === "deref") {
            this.emit(`$rt.panic("raw pointers are not available on the JS back end");`)
            return
        }
        const place = t.k === "field" ? `${this.expr(t.object)}${/^\d+$/.test(t.name) ? `[${t.name}]` : `.${t.name}`}` : this.expr(t)
        const v = this.expr(e.value)
        if (op === "=" ) { this.emit(`${place} = ${v};`); return }
        if (op === "/=" || op === "%=") { this.emit(`${place} = ${combine(place, v)};`); return }
        this.emit(`${place} ${op} ${v};`)
    }

    private closure(e: Extract<H.Expr, { k: "closure" }>): string {
        const ft = T.strip(e.ty)
        const params: string[] = []
        const prologue: string[] = []
        const cells: string[] = []
        e.params.forEach((p, i) => {
            const name = this.local(p.sym)
            const pt = ft.k === "fn" ? ft.params[i] ?? p.ty : p.ty
            if (needsCell(pt)) {
                const cell = `$c_${name}`
                params.push(cell)
                prologue.push(`let ${name} = ${cell}.v;`)
                cells.push(`${cell}.v = ${name};`)
            } else {
                params.push(name)
            }
        })
        const savedLoops = this.loops
        this.loops = []
        try {
            const body = this.capture(() => this.blockInto(e.body, RETURN))
            const inner = cells.length > 0 ? [...prologue, "try {", ...indent(body), `} finally { ${cells.join(" ")} }`] : body
            return `((${params.join(", ")}) => {\n${indent(inner).join("\n")}\n})`
        } finally {
            this.loops = savedLoops
        }
    }
}

function isBig(t: Ty): boolean {
    const s = T.strip(t)
    return s.k === "prim" && (s.name === "i64" || s.name === "u64")
}

/** `&mut T` parameters use the cell protocol (see `callWithCells`). */
function witnessVar(s: Sym): string {
    return `$w_${s.name}${s.id}`
}

function needsCell(t: Ty): boolean {
    const p = T.prune(t)
    return p.k === "ref" && p.mut
}

function nullLit(e: H.Expr): H.Expr {
    return { k: "lit", ty: T.UNKNOWN, span: e.span, value: null }
}
